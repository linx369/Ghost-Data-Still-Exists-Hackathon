"""Reports written by every full run: token usage/cost and the provenance (certainty) of every link."""
from __future__ import annotations

from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from .llm import PRICES, USAGE


def write_usage_report(path: Path, n_requests: int, split: str, offline: bool) -> None:
    u = USAGE.as_dict()
    lines = [
        "# Token usage and cost — final full-dataset run",
        "",
        f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')} by `python code/main.py`"
        f"{' --offline' if offline else ''} (split: `{split}`, {n_requests} requests).",
        "- Provider: **Anthropic (Claude API)**. Prices used for estimates (USD per million tokens, input / output): "
        + ", ".join(f"`{m}` {p[0]:.2f} / {p[1]:.2f}" for m, p in PRICES.items()) + ".",
        "- Model calls happen only for (a) reading the 11 screenshots + 4 PDFs once and (b) classifying each",
        "  *distinct* request text once (batched 40 per call). Everything else is deterministic Python, so the",
        "  per-request cost is the amortized cost of those calls. Every answer is cached in `code/cache/`;",
        "  `cache hits` below are calls served from that cache (no tokens billed in this run).",
        "",
        "| Model | API calls | cache hits | input tokens | output tokens | total tokens | est. cost (USD) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    tot = {"calls": 0, "cache_hits": 0, "input_tokens": 0, "output_tokens": 0, "cost_usd": 0.0}
    for m, d in u.items():
        billed_calls = d["calls"] - d["cache_hits"]
        lines.append(f"| `{m}` | {billed_calls} | {d['cache_hits']} | {d['input_tokens']:,} | {d['output_tokens']:,} | "
                     f"{d['input_tokens'] + d['output_tokens']:,} | {d['cost_usd']:.4f} |")
        for k in tot:
            tot[k] += d[k]
    total_tokens = tot["input_tokens"] + tot["output_tokens"]
    lines += [
        f"| **Overall** | {tot['calls'] - tot['cache_hits']} | {tot['cache_hits']} | {tot['input_tokens']:,} | "
        f"{tot['output_tokens']:,} | {total_tokens:,} | {tot['cost_usd']:.4f} |",
        "",
        "Token counts include calls served from cache (the tokens those answers originally cost), so the",
        "figures describe the full cost of producing this output, not only what was billed in this run.",
        "",
        "| Per request (÷ %d) | value |" % n_requests,
        "|---|---:|",
        f"| average total tokens | {total_tokens / n_requests:,.1f} |",
        f"| average input tokens | {tot['input_tokens'] / n_requests:,.1f} |",
        f"| average output tokens | {tot['output_tokens'] / n_requests:,.1f} |",
        f"| average model calls | {tot['calls'] / n_requests:.3f} |",
        f"| estimated cost | ${tot['cost_usd'] / n_requests:.5f} |",
        "",
        "Why it is cheap: the model *describes* (artifact facts, request intent) once per distinct input;",
        "deterministic code *decides* per case. A naive agent-per-case design would re-read evidence for",
        "every one of the 518 requests.",
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


ACCOUNT_LINKS = [
    ("direct", "an evidence record ties the account to the person's identifiers", "established"),
    ("direct-multi", "several proven accounts; the one the worker processed", "established"),
    ("window", "worker deleted it in the measured window, no other owner, result matches the claim", "inferred, validated out-of-sample (0 wrong)"),
    ("window+signature", "as above, tie broken by the worker's timing grid", "inferred, validated out-of-sample (0 wrong)"),
    ("same-user-other-case", "same person's account from another request", "inferred"),
    ("unresolved-tie", "evidence fits several requests equally; deterministic pick", "**uncertain (~chance)**"),
    ("none", "no account could be linked", "missing"),
]
ANALYTICS_LINKS = [
    ("timing-grid", "unique fit on the worker's timing grid", "inferred"),
    ("unresolved-tie", "several requests fit equally; deterministic pick", "**uncertain (~chance)**"),
]


def write_uncertainty_report(path: Path, results) -> None:
    acc = Counter(r.trace.get("account", {}).get("link") for r in results if "account" in r.trace)
    an = Counter(x[2] for r in results for x in r.trace.get("activity_linked", []))
    unsure = sorted((r for r in results if r.trace.get("uncertain")), key=lambda r: int(r.case_id.split("_")[1]))
    lines = ["# Uncertainty report — how each link in output.csv was established", "",
             "Generated by every full run (`python code/main.py`). Policy (Tom's decision): when the evidence",
             "cannot separate several requests, the output still contains the step the contract requires, picked",
             "deterministically, and the pick is reported here as uncertain rather than presented as a fact.", "",
             "## Account links", "", "| Link | Meaning | Confidence | Requests |", "|---|---|---|---:|"]
    lines += [f"| `{k}` | {m} | {c} | {acc.get(k, 0)} |" for k, m, c in ACCOUNT_LINKS]
    lines += ["", "## Already-anonymized analytics links", "", "| Link | Meaning | Confidence | Requests |",
              "|---|---|---|---:|"]
    lines += [f"| `{k}` | {m} | {c} | {an.get(k, 0)} |" for k, m, c in ANALYTICS_LINKS]
    lines += ["", f"## Requests containing an uncertain step ({len(unsure)})", "",
              "| Request | Uncertain resource(s) |", "|---|---|"]
    lines += [f"| {r.case_id} | {', '.join(r.trace['uncertain'])} |" for r in unsure]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
